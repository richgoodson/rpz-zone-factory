"""Pi-hole flat blocklist renderer.

Outputs one domain per line. CIDR/IP entries are skipped since Pi-hole
custom blocklists only support domain-based blocking.
"""

from __future__ import annotations

import logging
from io import StringIO

from rpz_factory.models import EntryType, ThreatEntry

logger = logging.getLogger(__name__)


def render(entries: list[ThreatEntry]) -> str:
    """Render a list of ThreatEntry objects as a Pi-hole flat domain list.

    Only domain-type entries are included. IP/CIDR entries are logged and skipped.
    """
    buf = StringIO()
    buf.write("# Pi-hole blocklist generated by rpz-zone-factory\n")
    buf.write("# One domain per line\n")
    buf.write("#\n\n")

    domain_count = 0
    skipped = 0

    seen: set[str] = set()
    for entry in entries:
        if entry.entry_type != EntryType.DOMAIN:
            skipped += 1
            continue

        domain = entry.normalized_value()
        if domain in seen:
            continue
        seen.add(domain)

        buf.write(f"{domain}\n")
        domain_count += 1

    if skipped:
        logger.info(
            "Pi-hole renderer: skipped %d non-domain entries (IP/CIDR)", skipped
        )
    logger.info("Pi-hole renderer: wrote %d domains", domain_count)

    return buf.getvalue()
