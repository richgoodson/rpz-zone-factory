"""RFC 5782 RPZ zone file renderer.

Produces a valid zone file with SOA, NS, and CNAME . records
suitable for loading into BIND as a response policy zone.
"""

from __future__ import annotations

import datetime
import logging
from io import StringIO

from rpz_factory.models import EntryType, ThreatEntry

logger = logging.getLogger(__name__)


def render(
    entries: list[ThreatEntry],
    zone_name: str = "rpz.local",
    ttl: int = 300,
    soa_refresh: int = 3600,
    soa_retry: int = 600,
    soa_expire: int = 604800,
    soa_minimum: int = 60,
) -> str:
    """Render a list of ThreatEntry objects as an RFC 5782 RPZ zone file."""
    serial = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%d%H")
    buf = StringIO()

    # Header comment
    buf.write(f"; RPZ zone file generated by rpz-zone-factory\n")
    buf.write(f"; Zone: {zone_name}\n")
    buf.write(f"; Generated: {datetime.datetime.now(datetime.timezone.utc).isoformat()}\n")
    buf.write(f"; Entries: {len(entries)}\n")
    buf.write(";\n\n")

    # TTL directive
    buf.write(f"$TTL {ttl}\n\n")

    # SOA record
    buf.write(f"@ IN SOA {zone_name}. hostmaster.{zone_name}. (\n")
    buf.write(f"    {serial}  ; serial\n")
    buf.write(f"    {soa_refresh}       ; refresh\n")
    buf.write(f"    {soa_retry}        ; retry\n")
    buf.write(f"    {soa_expire}     ; expire\n")
    buf.write(f"    {soa_minimum}         ; minimum TTL\n")
    buf.write(")\n\n")

    # NS record (required, points to localhost as this is policy-only)
    buf.write(f"@ IN NS LOCALHOST.\n\n")

    # RPZ entries
    buf.write("; --- Threat entries ---\n\n")

    for entry in entries:
        if entry.entry_type == EntryType.DOMAIN:
            domain = entry.normalized_value()
            # Block the domain and all subdomains
            buf.write(f"{domain}.{zone_name}. CNAME .\n")
            buf.write(f"*.{domain}.{zone_name}. CNAME .\n")

        elif entry.entry_type == EntryType.IP:
            # RPZ IP trigger: encode IP in reverse + prefix length
            # For a single IP: 32.<reverse-ip>.rpz-ip
            ip = entry.normalized_value()
            octets = ip.split(".")
            reversed_ip = ".".join(reversed(octets))
            buf.write(f"32.{reversed_ip}.rpz-ip.{zone_name}. CNAME .\n")

        elif entry.entry_type == EntryType.CIDR:
            # RPZ IP-trigger CIDR: <prefix-len>.<reversed-network>.rpz-ip
            # All 4 octets must be included in the reversed address — stripping
            # trailing zero octets reduces the implied bit count to equal the
            # prefix length, leaving zero host bits, which BIND rejects with
            # "too small prefix length".
            # Also skip overly broad prefixes (< /24) which BIND rejects by default.
            cidr = entry.normalized_value()
            if "/" in cidr:
                network, prefix_str = cidr.split("/", 1)
                prefix_len = int(prefix_str)
                if prefix_len < 24:
                    logger.debug(
                        "Skipping CIDR %s: prefix /%d is below BIND RPZ minimum of /24",
                        cidr,
                        prefix_len,
                    )
                    continue
                octets = network.split(".")
                # Always include all 4 octets in reversed order
                reversed_network = ".".join(reversed(octets))
                buf.write(
                    f"{prefix_len}.{reversed_network}.rpz-ip.{zone_name}. CNAME .\n"
                )

    return buf.getvalue()
