"""RFC 5782 RPZ zone file renderer.

Produces a valid zone file with SOA, NS, and CNAME . records
suitable for loading into BIND as a response policy zone.
"""

from __future__ import annotations

import datetime
import logging
import os
import re
from io import StringIO

from rpz_factory.models import EntryType, ThreatEntry

logger = logging.getLogger(__name__)

# Matches a plaintext zone file SOA serial line produced by this renderer,
# e.g. "    2026040803  ; serial".
_SERIAL_LINE_RE = re.compile(r"^\s*(\d+)\s*;\s*serial\b", re.IGNORECASE)


def read_serial_from_zone_file(path: str) -> int | None:
    """Return the SOA serial from a text RPZ zone file, or None if unreadable.

    Only reads the first ~50 lines — the SOA is always near the top. Returns
    None for missing files, unparseable files, or binary (raw) zone files
    where the SOA is not ASCII text.
    """
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            for i, line in enumerate(f):
                if i > 50:
                    break
                m = _SERIAL_LINE_RE.match(line)
                if m:
                    return int(m.group(1))
    except (OSError, ValueError):
        pass
    return None


def compute_next_serial(existing_path: str | None = None) -> int:
    """Compute the next SOA serial in YYYYMMDDNN format.

    NN is a 2-digit revision counter (00-99) that increments every time we
    render on the same UTC day. Rolls over to 00 on a new day.

    If `existing_path` is provided and points to a readable text zone file,
    its current serial is parsed and used as the baseline. Otherwise we start
    at NN=00 for today.

    Behavior:
      * existing=None or unreadable       → YYYYMMDD00 for today
      * existing date != today            → YYYYMMDD00 for today
      * existing date == today, NN < 99   → existing+1
      * existing date == today, NN == 99  → existing+1 = YYYYMMDD100 (overflow)
      * existing > today (e.g. BIND auto-bumped past us) → existing+1

    The "existing > today" case matters for incremental zones: BIND may have
    auto-incremented the serial via nsupdate since our last run. We always
    produce a serial strictly greater than what's on disk so BIND never sees
    a regression.
    """
    today = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%d")
    today_base = int(today) * 100  # YYYYMMDD00

    existing = None
    if existing_path:
        existing = read_serial_from_zone_file(existing_path)

    if existing is None:
        return today_base

    # If the existing serial is from an earlier day, reset NN to 00 for today.
    # Compare date portion (first 8 digits).
    existing_date = existing // 100
    today_date = int(today)

    if existing_date < today_date:
        return today_base

    # Same day or future (BIND bumped past us) — always return existing+1.
    return existing + 1


def render(
    entries: list[ThreatEntry],
    zone_name: str = "rpz.local",
    ttl: int = 300,
    soa_refresh: int = 3600,
    soa_retry: int = 600,
    soa_expire: int = 604800,
    soa_minimum: int = 60,
    serial: int | str | None = None,
) -> str:
    """Render a list of ThreatEntry objects as an RFC 5782 RPZ zone file.

    If `serial` is provided (as int or string of digits), it is used verbatim.
    Otherwise falls back to YYYYMMDDHH from the current UTC time. Callers that
    need monotonic serials (e.g. for IXFR) should compute the next serial via
    `compute_next_serial()` and pass it in.
    """
    if serial is None:
        serial = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%d%H")
    buf = StringIO()

    # Header comment
    buf.write(f"; RPZ zone file generated by rpz-zone-factory\n")
    buf.write(f"; Zone: {zone_name}\n")
    buf.write(f"; Generated: {datetime.datetime.now(datetime.timezone.utc).isoformat()}\n")
    buf.write(f"; Entries: {len(entries)}\n")
    buf.write(";\n\n")

    # TTL directive
    buf.write(f"$TTL {ttl}\n\n")

    # SOA record
    buf.write(f"@ IN SOA {zone_name}. hostmaster.{zone_name}. (\n")
    buf.write(f"    {serial}  ; serial\n")
    buf.write(f"    {soa_refresh}       ; refresh\n")
    buf.write(f"    {soa_retry}        ; retry\n")
    buf.write(f"    {soa_expire}     ; expire\n")
    buf.write(f"    {soa_minimum}         ; minimum TTL\n")
    buf.write(")\n\n")

    # NS record (required, points to localhost as this is policy-only)
    buf.write(f"@ IN NS LOCALHOST.\n\n")

    # RPZ entries
    buf.write("; --- Threat entries ---\n\n")

    for entry in entries:
        if entry.entry_type == EntryType.DOMAIN:
            domain = entry.normalized_value()
            # Block the domain and all subdomains
            buf.write(f"{domain}.{zone_name}. CNAME .\n")
            buf.write(f"*.{domain}.{zone_name}. CNAME .\n")

        elif entry.entry_type == EntryType.IP:
            # RPZ IP trigger: encode IP in reverse + prefix length
            # For a single IP: 32.<reverse-ip>.rpz-ip
            ip = entry.normalized_value()
            octets = ip.split(".")
            reversed_ip = ".".join(reversed(octets))
            buf.write(f"32.{reversed_ip}.rpz-ip.{zone_name}. CNAME .\n")

        elif entry.entry_type == EntryType.CIDR:
            # RPZ IP-trigger CIDR: <prefix-len>.<reversed-network>.rpz-ip
            # All 4 octets must be included in the reversed address — stripping
            # trailing zero octets reduces the implied bit count to equal the
            # prefix length, leaving zero host bits, which BIND rejects with
            # "too small prefix length".
            # BIND accepts rpz-ip prefixes /1-/32, so there is no lower bound on
            # how broad a block may be. The one exception is /0: rpz-ip has no
            # encoding for a zero-length prefix (split into two /1s upstream if
            # you truly need to match everything), so drop it rather than emit a
            # record BIND will reject at zone load.
            cidr = entry.normalized_value()
            if "/" in cidr:
                network, prefix_str = cidr.split("/", 1)
                prefix_len = int(prefix_str)
                if prefix_len < 1:
                    logger.debug(
                        "Skipping CIDR %s: rpz-ip cannot encode a /0 prefix", cidr
                    )
                    continue
                octets = network.split(".")
                # Always include all 4 octets in reversed order
                reversed_network = ".".join(reversed(octets))
                buf.write(
                    f"{prefix_len}.{reversed_network}.rpz-ip.{zone_name}. CNAME .\n"
                )

    return buf.getvalue()
